"""G3 mask/position oracle.

Goldens come from the pinned read-only reference: the boolean 2D mask is produced
by ``lerobot.policies.common.vla_utils.make_att_2d_masks`` itself, and the two
post-steps (suffix-to-FAST blocking, FAST-parallel suffix positions, per-draw
block diagonal) are transcribed from the named reference functions below.

No candidate code is imported, so these arrays cannot be generated by the thing
under test.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path

import numpy as np
import torch
from lerobot.policies.common.vla_utils import make_att_2d_masks


def digest_arrays(arrays: dict) -> dict:
    out = {}
    for name, value in arrays.items():
        payload = np.ascontiguousarray(value)
        out[name] = {
            "shape": list(payload.shape),
            "dtype": str(payload.dtype),
            "sha256": hashlib.sha256(payload.tobytes()).hexdigest(),
        }
    return out


def _supervised_causal(mask: torch.Tensor, labels: torch.Tensor, lang_start: int):
    """Supervised text rows must see exactly the preceding supervised columns."""
    supervised = (labels != -100).nonzero().flatten() + lang_start
    if supervised.numel() == 0:
        return None
    block = mask[supervised][:, supervised]
    expected = torch.tril(torch.ones(supervised.numel(), supervised.numel(), dtype=torch.bool))
    return bool((block == expected).all())


def build_case(cameras: int, image_tokens: int, text_len: int, fast_len: int, chunk: int,
               draws: int, text_targets: int, camera_mask: list[bool] | None = None,
               text_valid: int | None = None, fast_valid: int | None = None) -> dict:
    batch = 1
    pads, atts = [], []
    valid_cameras = camera_mask or [True] * cameras
    for index in range(cameras):
        pads.append(torch.full((batch, image_tokens), bool(valid_cameras[index])))
        atts.append(torch.zeros(batch, image_tokens, dtype=torch.int32))
    text_valid = text_len if text_valid is None else text_valid
    text_pad = torch.zeros(batch, text_len, dtype=torch.bool)
    text_pad[:, :text_valid] = True
    labels = torch.full((batch, text_len), -100, dtype=torch.long)
    if text_targets:
        labels[:, text_valid - text_targets : text_valid] = torch.arange(text_targets)[None]
    pads.append(text_pad)
    # Reference: _mark_target_span_causal — supervised targets start a new block.
    atts.append((labels != -100).to(torch.int32))
    fast_valid = fast_len if fast_valid is None else fast_valid
    fast_pad = torch.zeros(batch, fast_len, dtype=torch.bool)
    fast_pad[:, :fast_valid] = True
    pads.append(fast_pad)
    # Reference: _embed_supervised_prefix — every FAST token carries att=1.
    atts.append(torch.ones(batch, fast_len, dtype=torch.int32))

    prefix_pad = torch.cat(pads, dim=1)
    prefix_att = torch.cat(atts, dim=1)
    prefix_len = prefix_pad.shape[1]
    non_fast_len = prefix_len - fast_len
    suffix_pad = torch.ones(batch, chunk, dtype=torch.bool)
    suffix_att = torch.zeros(batch, chunk, dtype=torch.int32)
    suffix_att[:, 0] = 1

    if draws == 1:
        pad = torch.cat([prefix_pad, suffix_pad], dim=1)
        att = torch.cat([prefix_att, suffix_att], dim=1)
        mask = make_att_2d_masks(pad, att)
        if fast_len > 0:
            mask[:, prefix_len:, non_fast_len:prefix_len] = False
        positions = torch.cumsum(pad.to(torch.int32), dim=1) - 1
        if fast_len > 0:
            non_fast_valid = prefix_pad[:, :non_fast_len].sum(dim=1, keepdim=True)
            suffix_pos = non_fast_valid + torch.cumsum(suffix_pad.to(torch.int32), dim=1) - 1
            positions = torch.cat([positions[:, :prefix_len], suffix_pos], dim=1)
    else:
        total = draws * chunk
        prefix_2d = make_att_2d_masks(prefix_pad, prefix_att)
        prefix_rows = torch.cat(
            [prefix_2d, torch.zeros(batch, prefix_len, total, dtype=torch.bool)], dim=2)
        action_to_prefix = prefix_pad[:, None, :].expand(batch, total, prefix_len).clone()
        if fast_len > 0:
            action_to_prefix[:, :, non_fast_len:prefix_len] = False
        block = torch.block_diag(*[torch.ones(chunk, chunk, dtype=torch.bool) for _ in range(draws)])
        action_rows = torch.cat([action_to_prefix, block[None].expand(batch, total, total)], dim=2)
        mask = torch.cat([prefix_rows, action_rows], dim=1)
        if fast_len > 0:
            offsets = prefix_pad[:, :non_fast_len].sum(dim=1, keepdim=True)
        else:
            offsets = prefix_pad.sum(dim=1, keepdim=True)
        block_positions = offsets + torch.cumsum(suffix_pad.to(torch.int32), dim=1) - 1
        positions = torch.cat(
            [torch.cumsum(prefix_pad.to(torch.int32), dim=1) - 1, block_positions.repeat(1, draws)],
            dim=1)

    m = mask[0]
    prefix_rows_sel = m[:prefix_len]
    action_rows_sel = m[prefix_len:]
    facts = {
        "prefix_to_action_any": bool(prefix_rows_sel[:, prefix_len:].any()),
        "action_to_prefix_any": bool(action_rows_sel[:, :prefix_len].any()),
        "action_to_fast_any": bool(action_rows_sel[:, non_fast_len:prefix_len].any()) if fast_len else False,
        "fast_to_text_any": bool(m[non_fast_len:prefix_len, non_fast_len - text_len:non_fast_len].any()) if fast_len else False,
        "text_target_causal": _supervised_causal(m, labels[0], non_fast_len - text_len) if text_targets else None,
        "draw_cross_visibility_any": bool(
            (m[prefix_len:, prefix_len:] != block[: total, : total]).any()) if draws > 1 else None,
        "suffix_position_offset": int(positions[0, prefix_len]) if positions.shape[1] > prefix_len else None,
        "non_fast_valid": int(prefix_pad[0, :non_fast_len].sum()),
        "mask_true_fraction": round(float(m.float().mean()), 6),
    }
    return {
        "prefix_pad": prefix_pad.numpy(),
        "prefix_att": prefix_att.numpy(),
        "suffix_pad": suffix_pad.numpy(),
        "suffix_att": suffix_att.numpy(),
        "mask": mask.numpy(),
        "positions": positions.numpy(),
        "meta": {"prefix_len": prefix_len, "non_fast_len": non_fast_len, "fast_len": fast_len,
                 "chunk": chunk, "draws": draws, "facts": facts},
    }


CASES = {
    "k1_base": dict(cameras=3, image_tokens=4, text_len=5, fast_len=3, chunk=4, draws=1, text_targets=2),
    "k1_right_pad": dict(cameras=2, image_tokens=4, text_len=6, fast_len=4, chunk=3, draws=1,
                         text_targets=2, text_valid=4, fast_valid=3),
    "k1_missing_camera": dict(cameras=3, image_tokens=4, text_len=5, fast_len=3, chunk=4, draws=1,
                              text_targets=2, camera_mask=[True, False, True]),
    "k5_base": dict(cameras=3, image_tokens=4, text_len=5, fast_len=3, chunk=4, draws=5, text_targets=2),
    "k5_fast_pad": dict(cameras=2, image_tokens=4, text_len=6, fast_len=6, chunk=3, draws=5,
                        text_targets=2, text_valid=5, fast_valid=4),
    "k5_no_fast": dict(cameras=2, image_tokens=4, text_len=4, fast_len=0, chunk=3, draws=5, text_targets=2),
}


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", required=True)
    parser.add_argument("--case", default=None)
    args = parser.parse_args()
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    names = [args.case] if args.case else list(CASES)
    arrays, meta = {}, {}
    for name in names:
        case = build_case(**CASES[name])
        for key in ("prefix_pad", "prefix_att", "suffix_pad", "suffix_att", "mask", "positions"):
            arrays[f"{name}__{key}"] = case[key]
        meta[name] = case["meta"]
    np.savez(out / "masks.npz", **arrays)
    manifest = {
        "schema": "fineart-jax-g3-masks/v1",
        "reference": {
            "root": os.environ.get("REFERENCE_ROOT"),
            "module": "lerobot.policies.common.vla_utils.make_att_2d_masks",
            "post_steps_from": [
                "lerobot/policies/fineart_vla/modeling_fineart_vla.py::_combined_prefix_and_flow",
                "lerobot/policies/fineart_vla/modeling_fineart_vla.py::_amortized_prefix_and_flow",
                "lerobot/policies/fineart_vla/modeling_fineart_vla.py::_mark_target_span_causal",
            ],
            "torch": torch.__version__,
            "numpy": np.__version__,
        },
        "cases": meta,
        "arrays": digest_arrays(arrays),
    }
    (out / "masks.json").write_text(json.dumps(manifest, indent=2, sort_keys=True) + "\n")
    summary = {name: meta[name]["facts"] for name in names}
    print(json.dumps(summary, indent=2)[:3000])


if __name__ == "__main__":
    main()
